export const useT = () => {
  const u = useCurrentUser();
  const lang: Lang = u?.language ?? "en";
  return (key: keyof typeof STR) => STR[key]?.[lang] ?? String(key);
};

export const t = (key: keyof typeof STR, lang: Lang) => STR[key]?.[lang] ?? String(key);

/** Returns the active language reactively. */
export const useLang = (): Lang => useCurrentUser()?.language ?? "en";

/** Inline translator: `tr("Hola", "Hello", "Zdravo")`. `sr` is optional and falls back to `en`. */
export const useTr = () => {
  const lang = useLang();
  return (es: string, en: string, sr?: string) =>
    lang === "es" ? es : lang === "sr" ? (sr ?? en) : en;
};
